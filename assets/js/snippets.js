/* Deigracht — панель сниппетов (snippets.js), волна v0.3.0 (fp №10,
   приоритет №1 владельца). Вставка заготовок блоков V3 и таблиц в точку
   курсора: новичок собирает статблок/врезку кнопкой, не заучивая синтаксис.
   Шаблоны — собственный текст проекта (CC0), форматирование статблока —
   по образцам SRD 5.1 (атрибуция — в справке, ЮР-03). */
'use strict';

DG.snippets = (function () {

  var L = [
    { id: 'note', label: 'Врезка {{note}}', text: [
      '{{note', 'Текст врезки: правило, напоминание, домашнее правило…', '}}', ''
    ].join('\n') },
    { id: 'wide', label: 'Широкий блок {{wide}}', text: [
      '{{wide', 'Текст или таблица во всю ширину разворота…', '}}', ''
    ].join('\n') },
    { id: 'descriptive', label: 'Флавор {{descriptive}}', text: [
      '{{descriptive', 'Флавор-текст: описание сцены, письмо, легенда…', '}}', ''
    ].join('\n') },
    { id: 'monster', label: 'Статблок {{monster}}', text: [
      '{{monster', '#### Название существа', '___',
      '*Средний размер, тип существа, мировоззрение*', '',
      '**Класс доспеха** 12 (природный)',
      '**Хиты** 22 (4d8 + 4)',
      '**Скорость** 30 фт.', '',
      '| STR | DEX | CON | INT | WIS | CHA |',
      '|---|---|---|---|---|---|',
      '| 14 (+2) | 12 (+1) | 13 (+1) | 6 (-2) | 10 (+0) | 8 (-1) |', '',
      '***Черта.*** Описание черты существа.', '',
      '### Действия', '',
      '***Атака.*** *Рукопашная:* +4 к попаданию, досягаемость 5 фт.,',
      'урон 5 (1d6 + 2) дробящего.',
      '}}', ''
    ].join('\n') },
    { id: 'toc', label: 'Оглавление {{toc}}', text: [
      '{{toc,wide', '- [{{ Название раздела}}{{ 2}}](#p2)',
      '- [{{ Подраздел}}{{ 3}}](#p3)', '}}', ''
    ].join('\n') },
    { id: 'table', label: 'Таблица', text: [
      '| Колонка А | Колонка Б | Колонка В |',
      '|---|:--:|---:|',
      '| значение | значение | значение |',
      '| значение | значение | значение |', ''
    ].join('\n') },
    { id: 'page', label: 'Разрыв страницы \\page', text: '\\page\n' },
    { id: 'cols', label: 'Одна колонка {{column-count:1}}', text: [
      '{{column-count:1', 'Текст в одну колонку (широкие таблицы, схемы)…', '}}', ''
    ].join('\n') },
    { id: 'h2', label: 'Заголовок раздела', text: '## Название раздела\n' },
    { id: 'quote', label: 'Цитата (чтение вслух)', text: [
      '> Текст для чтения вслух: описание комнаты, письмо, пророчество…', ''
    ].join('\n') }
  ];

  function list() { return L; }

  /* вставка в textarea: заменяет выделение, курсор — в конец вставки;
     дёргает input-событие для рендера/автосохранения (editor.js) */
  function insertInto(textarea, text) {
    var s = textarea.selectionStart || 0;
    var e = textarea.selectionEnd || 0;
    var v = textarea.value;
    /* вставка с новой строки: если курсор не на начале строки — добавим перенос */
    var pre = '';
    if (s > 0 && v[s - 1] !== '\n') pre = '\n';
    textarea.value = v.slice(0, s) + pre + text + v.slice(e);
    var pos = s + pre.length + text.length;
    textarea.setSelectionRange(pos, pos);
    textarea.focus();
    textarea.dispatchEvent(new Event('input', { bubbles: true }));
  }

  return { list: list, insertInto: insertInto };
})();
